export function getImageDimensions(src: string | undefined): ImageDimensions | null {
  if (!src) return null;
  return PROJECT_THUMBNAILS[src] ?? LOGOS[src] ?? null;
}

/**
 * Builds a `srcset` for a project thumbnail from its full-size WebP. The
 * `-480.webp` / `-960.webp` derivatives are generated by scripts/optimize-assets.sh.
 */
export function buildThumbnailSrcSet(src: string, width: number): string {
  const dot = src.lastIndexOf(".");
  const stem = dot >= 0 ? src.slice(0, dot) : src;
  const ext = dot >= 0 ? src.slice(dot) : "";

  const candidates: string[] = [`${src} ${width}w`];
  if (width > 960) candidates.push(`${stem}-960${ext} 960w`);
  if (width > 480) candidates.push(`${stem}-480${ext} 480w`);
  return candidates.join(", ");
}

/**
 * Approximate rendered width of a project thumbnail. Only affects which srcset
 * candidate the browser downloads — layout is fixed by the reserved dimensions
 * and `object-contain`.
 */
export const THUMBNAIL_SIZES = "(min-width: 1024px) 30vw, 60vw";
